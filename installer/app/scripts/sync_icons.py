"""Copy the icons the installer UI uses out of the Adobe track's generated icon set (read-only source).

    python installer/app/scripts/sync_icons.py           # (re)write installer/app/ui/js/icons.gen.js
    python installer/app/scripts/sync_icons.py --check   # exit 1 (naming each icon) when the subset drifted

Source: adobe/panel-ui/design/icons.js (Lucide, ISC, outlined to fill paths per size by its _build/build_icons.py).
The UI loads only this subset as an ES module (no 590 KB global script). Add a name to ICONS when a screen needs it;
the page self-check reports any icon a screen asks for that is not here ("missing=icon:<name>@<size>").
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import sys

APP = pathlib.Path(__file__).resolve().parents[1]
REPO = APP.parent.parent
SOURCE = REPO / "adobe" / "panel-ui" / "design" / "icons.js"
OUT = APP / "ui" / "js" / "icons.gen.js"

ICONS = [
    # the one status model (ok, warn, error, info, pending, busy, waiting, paused)
    "circle-check", "triangle-alert", "circle-x", "info", "circle-dashed", "loader-circle", "circle-dot", "circle-pause",
    # the shell: beta chip, trust line, Windows caption buttons
    "flask-conical", "shield-check", "minus", "square", "x",
    # the shared components (I.fail safety chip and support row, I.pathField, the demo body)
    "shield-x", "message-square", "copy", "download", "folder", "file-search", "refresh-cw",
]
PREFIX = "window.MOCK_ICONS="


def load_source() -> dict:
    text = SOURCE.read_text(encoding="utf-8")
    start = text.index(PREFIX) + len(PREFIX)
    return json.loads(text[start:text.rindex("}") + 1])


def subset(src: dict) -> dict:
    missing = [n for n in ICONS if n not in src]
    if missing:
        sys.exit(f"not in {SOURCE.name}: {', '.join(missing)}")
    return {n: src[n] for n in ICONS}


def render(data: dict) -> str:
    sha = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return ("/* GENERATED by installer/app/scripts/sync_icons.py from adobe/panel-ui/design/icons.js\n"
            f"   (sha256 {sha}). Do not edit; add names to ICONS there and re-run.\n"
            "   Lucide (ISC; the licence ships as vendor/licenses/lucide-LICENSE.txt, see ui/vendor.json), strokes outlined\n"
            "   into fill paths per size (12, 16, 20). Coloured by CSS fill classes only. */\n"
            "export default " + json.dumps(data, separators=(",", ":")) + ";\n")


def read_out() -> dict:
    text = OUT.read_text(encoding="utf-8")
    body = text.split("export default", 1)[1].strip()
    return json.loads(body[:-1])


def main() -> int:
    want = subset(load_source())
    if "--check" in sys.argv[1:]:
        if not OUT.exists():
            print(f"{OUT.name} is missing")
            return 1
        have = read_out()
        bad = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if bad:
            print("icons out of sync with the source: " + ", ".join(bad))
            return 1
        print(f"icons in sync: {len(want)}")
        return 0
    OUT.write_text(render(want), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO).as_posix()}: {len(want)} icons")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
