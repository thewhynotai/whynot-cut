// Compile the v4 contract checks the UXP host adapter runs in Premiere into plain JavaScript (ajv standalone), so the
// plugin validates every command's `$defs/data` and every readback it sends without shipping ajv itself (ajv compiles
// with `new Function`, which UXP does not allow; ajv's full bundle is about 280 KB unminified).
//   node scripts/gen-validators.mjs           -> writes src/ops/validators.gen.js and src/ops/validators.gen.d.ts
//   node scripts/gen-validators.mjs --check   -> exit 1 when the committed files differ from a fresh compile
// test/host-adapter-validators.test.ts runs --check, so a contract change that is not regenerated fails the tests.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { transformSync } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CONTRACT_DIR = join(root, "..", "..", "whynot-cut", "engine", "reel", "contract");
export const OUT_JS = join(root, "src", "ops", "validators.gen.js");
export const OUT_DTS = join(root, "src", "ops", "validators.gen.d.ts");
const ID_BASE = "https://thewhynot.ai/whynot-cut/contract/4/";

/** The actions the Premiere UXP host adapter implements this round (src/ops/index.ts CAPABILITIES; a test keeps them equal). */
export const OPS = ["ping", "status", "open_project", "set_player_position", "export_frames", "close_project_path", "clip_components"];

// ajv's code calls its runtime helper for minLength / maxLength (code-point length); it is inlined so the generated
// file has no import at all (same algorithm as ajv/dist/runtime/ucs2length, MIT).
const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
const UCS2_INLINE =
  "(function ucs2length(str){let length=0,pos=0,value;const len=str.length;while(pos<len){length++;value=str.charCodeAt(pos++);" +
  "if(value>=0xd800&&value<=0xdbff&&pos<len){value=str.charCodeAt(pos);if((value&0xfc00)===0xdc00)pos++;}}return length;})";

export function generate() {
  // the same strictness as test/contract.test.ts: unknown keywords fail loudly, the union-type shape rules are off
  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    strictSchema: true, strictTypes: false, strictRequired: false, strictTuples: false,
    allErrors: false, messages: false,
  });
  for (const f of readdirSync(CONTRACT_DIR).filter((n) => n.endsWith(".schema.json")).sort()) {
    ajv.addSchema(JSON.parse(readFileSync(join(CONTRACT_DIR, f), "utf8")));
  }
  const refs = {};
  for (const op of OPS) {
    refs[`${op}_data`] = `${ID_BASE}${op}.schema.json#/$defs/data`;
    refs[`${op}_readback`] = `${ID_BASE}${op}.schema.json#/$defs/readback`;
  }
  let code = standaloneCode(ajv, refs);
  code = code.split(UCS2).join(UCS2_INLINE);
  if (/\brequire\(/.test(code)) throw new Error("the generated validators still require() an ajv runtime module");
  const pretty = transformSync(code, { format: "esm", target: "es2022", legalComments: "none" }).code;
  const header =
    "// GENERATED by scripts/gen-validators.mjs from whynot-cut/engine/reel/contract/*.schema.json (ajv standalone).\n" +
    "// Do not edit: run `node scripts/gen-validators.mjs` after a contract change.\n";
  const js = header + pretty;
  const dts =
    header +
    "export interface GeneratedValidator {\n" +
    "  (data: unknown): boolean;\n" +
    "  errors?: Array<{ instancePath: string; keyword: string; params: Record<string, unknown> }> | null;\n" +
    "}\n" +
    Object.keys(refs).map((k) => `export declare const ${k}: GeneratedValidator;\n`).join("");
  return { js, dts };
}

const lf = (s) => s.replace(/\r\n/g, "\n");

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { js, dts } = generate();
  if (process.argv.includes("--check")) {
    const read = (p) => { try { return lf(readFileSync(p, "utf8")); } catch { return null; } };
    const stale = [[OUT_JS, js], [OUT_DTS, dts]].filter(([p, want]) => read(p) !== want).map(([p]) => p);
    if (stale.length) {
      console.error(`stale generated validators (run node scripts/gen-validators.mjs): ${stale.join(", ")}`);
      process.exit(1);
    }
    console.log("validators up to date");
  } else {
    writeFileSync(OUT_JS, js);
    writeFileSync(OUT_DTS, dts);
    console.log(`wrote ${OUT_JS} (${js.length} bytes) and ${OUT_DTS}`);
  }
}
