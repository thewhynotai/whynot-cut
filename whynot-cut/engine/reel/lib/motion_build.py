"""Build the native After Effects project of a motion video (spec §4.5, §4.7, §4.8).

The compiled motion-plan.json goes to After Effects as an ASCII JSON job; nh_motion_lib.jsx renders it (one comp per
scene, persistent layers and audio in MAIN_<id>, brand controls) and saves the .aep. Through the WhyNot Cut Bridge the
build is read back and compared with the plan; without the bridge, a self-contained fallback script is written
(SCRIPT_ONLY) or handed to AE with `AfterFX -r` (BUILT_UNVERIFIED: no read-back, QC cannot pass).
"""
from __future__ import annotations

import json
from pathlib import Path

from .common import TEMPLATES_DIR, now_iso, project_prefix, read_json, write_json, write_text

DEFAULT_CAPS = {"composer_universal": True, "rtl_direction": "textdocument", "word_index_logical": True,
                "fontobject": True, "emphasis_animator": True, "om_template": "High Quality"}


def aep_path(paths) -> Path:
    return paths.p(f"04_after_effects/project/{paths.video_id}_{project_prefix()}_MOTION.aep")


def render_path(paths) -> Path:
    return paths.p(f"04_after_effects/render/{paths.video_id}_MAIN.mov")


def capabilities() -> tuple[dict, str]:
    """The probe's measured capabilities when it has an ok verdict, else conservative defaults."""
    from .ae_probe import capabilities as probed
    rec = probed()
    if rec.get("verdict") == "ok" and rec.get("measured"):
        caps = dict(DEFAULT_CAPS, **rec["measured"])
        caps["word_index_logical"] = rec.get("word_index_logical", True) is not False
        return caps, "probe"
    return dict(DEFAULT_CAPS), "default"


def _line_cues(el: dict) -> list[int]:
    toks, out, k = el.get("tokens") or [], [], 0
    for ln in el.get("lines") or []:
        if toks:
            out.append(toks[min(k, len(toks) - 1)]["cue_frame"])
        k += len(ln.split())
    return out


def job_data(paths, fallback_font: str | None = None) -> dict:
    from .motion_config import motion_cfg
    plan = read_json(paths.p("01_analysis/motion-plan.json"))
    if not plan:
        raise SystemExit("01_analysis/motion-plan.json missing — run `reel motion-plan` first")
    caps, src = capabilities()
    scenes = plan["scenes"]
    for k, sc in enumerate(scenes):
        nxt = scenes[k + 1]["transition_in"]["frames"] if k + 1 < len(scenes) else 0
        sc["layer_out_frame"] = min(plan["duration_frames"], sc["end_frame"] + nxt)
        for el in sc["elements"]:
            if el.get("tokens") and not el.get("line_cues"):
                el["line_cues"] = _line_cues(el)
            if fallback_font and el.get("font_ps"):
                el["font_ps"] = fallback_font
    if fallback_font:
        for key in ("captions", "speaker_badge"):
            if (plan.get("persistent") or {}).get(key):
                plan["persistent"][key]["font_ps"] = fallback_font
    plan["word_reveal_s"] = round(int(motion_cfg().get("word_reveal_ms", 180)) / 1000, 3)
    return {"plan": plan, "caps": caps, "caps_source": src, "aep_path": str(aep_path(paths)),
            "render_path": str(render_path(paths)), "fallback_font": fallback_font, "generated": now_iso()}


def write_job(paths, **kw) -> Path:
    job = job_data(paths, **kw)
    p = paths.p("04_after_effects/data/motion-job.json")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(job, ensure_ascii=True), encoding="ascii")
    for d in (aep_path(paths).parent, render_path(paths).parent):   # ExtendScript never creates folders itself
        d.mkdir(parents=True, exist_ok=True)
    return p


def write_fallback_script(paths, **kw) -> Path:
    job = job_data(paths, **kw)
    for d in (aep_path(paths).parent, render_path(paths).parent):
        d.mkdir(parents=True, exist_ok=True)
    lib = (TEMPLATES_DIR / "after_effects/nh_ae_lib.jsx").read_text(encoding="utf-8")
    mlib = (TEMPLATES_DIR / "after_effects/nh_motion_lib.jsx").read_text(encoding="utf-8")
    js = ("// AUTO-GENERATED by whynot-cut motion mode — " + now_iso() + "\n"
          "// Fallback (no bridge): File > Scripts > Run Script File... in After Effects, or `reel motion-build --run-script`.\n"
          "var NH_JOB = " + json.dumps(job, ensure_ascii=True) + ";\n"
          "var NH_DATA = {brand: NH_JOB.plan.brand};\n" + lib + "\n" + mlib + "\n"
          "app.beginUndoGroup(\"whynot-cut motion\");\napp.newProject();\nNHM.build(NH_JOB);\napp.endUndoGroup();\n")
    out = paths.p(f"04_after_effects/scripts/build_{paths.video_id}_motion.jsx")
    write_text(out, js)
    return out
