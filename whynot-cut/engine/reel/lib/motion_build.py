RESULT = "04_after_effects/motion-build-result.json"


def _sha1(p: Path) -> str:
    import hashlib
    return hashlib.sha1(p.read_bytes()).hexdigest() if p.exists() else ""


def _inner(r: dict) -> dict:
    return ((r or {}).get("response") or {}).get("result") or {}


def editor_changed(paths) -> bool:
    """The .aep differs from the one this pipeline last saved (the editor worked in it)."""
    prior = read_json(paths.p(RESULT), {}) or {}
    aep = aep_path(paths)
    return bool(aep.exists() and prior.get("aep_sha1") and _sha1(aep) != prior["aep_sha1"])


def _plan_fonts(plan: dict) -> list[str]:
    names = {e.get("font_ps") for s in plan["scenes"] for e in s["elements"] if e.get("font_ps")}
    for key in ("captions", "speaker_badge"):
        f = ((plan.get("persistent") or {}).get(key) or {}).get("font_ps")
        if f:
            names.add(f)
    return sorted(n for n in names if n)


# BL-21: what the editor reads when a build of any route is refused for its approval (the 2.x case: plan.OLDER_APPROVAL)
GATE_EDITOR = {
    "none": {"en": "The motion plan is not approved yet. Look at the plan and the animatic, then approve it.",
             "ar": "خطة الموشن لسه متوافقش عليها. بص على الخطة والأنيماتيك، وبعدين وافق عليها."},
    "stale": {"en": "The motion plan changed after you approved it. Have one more look and approve it again.",
              "ar": "خطة الموشن اتغيّرت بعد ما وافقت عليها. بص عليها بصّة كمان ووافق عليها تاني."}}


def plan_gate(paths) -> tuple[list[str], dict | None]:
    """The compiled plan and its approval, checked the same way for every motion build route (the bridge build,
    --script-only, --run-script): (problems, refusal). A problem is something to fix (exit 1); the refusal
    {blocked, how, editor_message EN/AR} is a missing, stale or 2.x approval (exit 2). A compiled plan edited by hand
    (review 91b6b44 P2-1) is refused first, with no `blocked` (exit 1) and its own EN/AR line: it is compiled again
    before anything else."""
    from .motion_plan import PLAN_EDITED, fingerprint, plan_edited
    probs, stale = [], False
    val = read_json(paths.p("01_analysis/motion-validation.json"), {}) or {}
    fp = fingerprint(paths)
    if not paths.p("01_analysis/motion-plan.json").exists() or not val:
        probs.append("no compiled motion plan: run `reel motion-plan`")
    elif not val.get("ok"):
        probs.append("the motion plan has errors: fix them (01_analysis/motion-plan.md)")
    elif val.get("fingerprint") != fp:
        probs.append("the motion plan is stale (script, words, audio, music/licences, brand or the names shown changed): run `reel motion-plan` again")
        stale = True
    else:
        edited = plan_edited(paths)
        if edited:
            return probs + [edited], {"how": "Run `reel motion-plan` again: it writes the plan from the script, the "
                                             "transcript and the episode sheet (a change made only in motion-plan.json "
                                             "is not kept); then motion-build again",
                                      "editor_message": dict(PLAN_EDITED)}
    appr = read_json(paths.p("01_analysis/plan-approval.json"), {}) or {}
    from .plan import OLDER_APPROVAL, approved_before_3
    older = approved_before_3(appr) and appr.get("plan_fingerprint") != fp          # 3.0 F2: approved under 2.x
    gate, says = None, None
    if not appr.get("approved"):
        gate = "the plan is not approved yet: the editor approves motion-plan.md and the animatic (`reel approve-plan`)"
        says = GATE_EDITOR["none"]
    elif appr.get("plan_fingerprint") != fp:
        gate = (OLDER_APPROVAL["en"] if older else
                "the plan approval is stale (the plan changed after approval): show the editor again")
        says = OLDER_APPROVAL if older else GATE_EDITOR["stale"]
    if not gate:
        return probs, None
    probs.append(gate)          # an approval gate is a refusal (exit 2), like ppro-build's (Gate 2 A2)
    how = ("Show the editor motion-plan.md and the animatic; only with their words run `reel approve-plan --by "
           "editor`, then motion-build again")
    if stale:                   # review 91b6b44 P3-3: the plan is compiled again first, then shown and approved
        how = "Run `reel motion-plan` again first (its inputs changed after it was compiled). Then " + how[0].lower() + how[1:]
    return probs, {"blocked": gate, "how": how, "editor_message": dict(says)}


def _route_refused(paths) -> dict | None:
    """BL-21: --script-only / --run-script refused like the bridge build, before any script is written or After
    Effects is asked anything."""
    probs, refusal = plan_gate(paths)
    if not probs:
        return None
    return dict({"status": "REFUSED", "ok": False, "reasons": probs, "aep": str(aep_path(paths))}, **(refusal or {}))


def preconditions(paths, allow_fallback_font: bool = False) -> tuple[list[str], dict]:
    from . import ae_bridge, ae_probe, plat
    ctx = {"missing_fonts": []}
    if not plat.newest_app("after_effects"):
        return ["After Effects is not installed: deliver the script with `reel motion-build --script-only`"], ctx
    probs, refusal = plan_gate(paths)
    if refusal:
        ctx["refusal"] = refusal
    st = ae_bridge.status()
    if not st.get("alive"):
        probs.append(f"the WhyNot Cut Bridge is not running in After Effects: {st.get('detail')} (`reel ae-status`)")
        return probs, ctx
    if "bridge_version" in st:          # a heartbeat that names its version must be this engine's bridge
        from .cep_queue import version_refusal
        from .ppro_bridge import BRIDGE_VERSION
        refused = version_refusal(st, BRIDGE_VERSION, "After Effects")
        if refused:
            probs.append(f"{refused['error']}: {refused['how']}")
            ctx["refusal"] = {"blocked": refused["blocked"], "how": refused["how"]}     # a refusal: exit 2
            return probs, ctx
    # `busy` comes from the bridge's daemon alone (3.1.1): another session's build waits on the build lock instead,
    # so busy here is a short job (a ping, a probe) of someone else
    if st.get("busy"):
        probs.append("After Effects is busy with another bridge job: try again when it finishes")
    ping = _inner(ae_bridge.submit("ping", {}, timeout=60))
    ctx["ping"] = ping
    ver = ping.get("ae_version")
    if not ae_probe.verdict_ok(ver):
        probs.append(f"no ok Arabic probe verdict for After Effects {ver}: run `reel ae-probe`, view the frames, record it")
    target = str(aep_path(paths))
    dirty = ping.get("dirty")      # None = AE could not say: never treat as clean (the build opens a new project)
    if dirty is not False and not (dirty is None and not ping.get("project_path") and ping.get("num_items") == 0):
        same = bool(ping.get("project_path")) and Path(ping["project_path"]).resolve() == Path(target).resolve()
        where = " in this reel's project" if same else f" in {ping.get('project_path') or 'an untitled project'}"
        what = "has unsaved changes" if dirty is True else "could not report whether it has unsaved changes"
        probs.append(f"After Effects {what}{where}: save or close it in After Effects first")
    from .stamps import read_compiled
    plan = read_compiled(paths.p("01_analysis/motion-plan.json"), {}) or {}
    if plan:
        fonts = _inner(ae_bridge.submit("fonts", {"postscript_names": _plan_fonts(plan)}, timeout=60)).get("fonts") or {}
        miss = [n for n, f in fonts.items() if not f.get("found") or f.get("substitute")]
        ctx["missing_fonts"] = miss
        if miss and not allow_fallback_font:
            from .plat import font_install_hint
            probs.append(f"font(s) not installed for After Effects: {', '.join(miss)} - install them from assets/Fonts "
                         f"({font_install_hint()}), restart After Effects; or, only with the editor's OK, --allow-fallback-font")
    return probs, ctx


def _record(paths, res: dict) -> dict:
    write_json(paths.p(RESULT), dict(res, at=now_iso()))
    return res


LOCK_HOLD_S = 3600          # the expiry written in the lock: honoured for holders on OTHER computers only (a live holder here is never stale)


def build(paths, replace_edited: bool = False, allow_fallback_font: bool = False, timeout: int = 900, *,
          lock_wait_s: float | None = None) -> dict:
    """One After Effects build at a time on this machine (the bridge's build lock on ae-queue): a second session
    waits up to `lock_wait_s` (default cep_queue.LOCK_WAIT_S), then gets REFUSED with `blocked`."""
    from . import ae_bridge, cep_queue
    wait = cep_queue.LOCK_WAIT_S if lock_wait_s is None else lock_wait_s
    made = {}                           # the backup _build_locked made, for a full disk below
    try:
        with ae_bridge.build_lock(f"motion-build {paths.video_id}", hold_s=LOCK_HOLD_S, wait_s=wait):
            return _build_locked(paths, replace_edited, allow_fallback_font, timeout, made)
    except cep_queue.BuildLockBusy as e:
        r = cep_queue.lock_busy_result(e, "After Effects")
        return dict(r, status="REFUSED", reasons=[r["blocked"]], aep=str(aep_path(paths)), fallback_font=None)
    except OSError as e:                # G2 R1: a full disk in plain words, with the .aep it replaced put back
        import shutil
        from .build_safety import disk_full_message, is_disk_full
        if not is_disk_full(e):
            raise
        aep, bak, restored = aep_path(paths), made.get("backup"), False
        if bak and bak.exists() and (not aep.exists() or _sha1(aep) != _sha1(bak)):
            try:
                shutil.copy2(bak, aep)
                restored = True
            except OSError:
                pass
        msg = disk_full_message(aep)
        how = ("The previous .aep was put back." if restored else
               f"The previous .aep is kept as backups/{bak.name}." if bak else "Nothing of the old project was changed.")
        return {"status": "FAILED", "ok": False, "error": msg, "reasons": [msg], "how": how, "aep": str(aep),
                "fallback_font": None, "previous_restored": restored}


def build_for_serve(data: dict, *, lock_wait_s: float | None = None) -> dict:
    """`reel serve`'s ae_build_motion (Addendum G2 R1): the CLI's `reel motion-build`, never the raw bridge action. The
    reel is the one whose .aep the request's job.aep_path names; build() then runs the CLI's gates (Gate 1 approval of
    the current motion plan, the editor-changed check, After Effects' unsaved work, fonts, free space) under the build
    lock and backs the .aep up first. --replace-edited and --allow-fallback-font are never available from serve; the
    job is made from the approved plan, the request's job is not used."""
    from .build_safety import reel_for_target, serve_context
    from .common import use_context
    job = (data or {}).get("job")
    target = job.get("aep_path") if isinstance(job, dict) else None
    paths, why = reel_for_target(target, "04_after_effects/project")
    ctx = serve_context(paths.root) if paths else None
    if paths and ctx is None:
        why = "The .aep is in another client folder than the request: nothing was built."
    if not why:
        with use_context(ctx):
            if Path(target).resolve() != aep_path(paths).resolve():
                why = f"{Path(target).name} is not this reel's .aep ({aep_path(paths).name}): nothing was built."
            else:
                return build(paths, lock_wait_s=lock_wait_s)
    return {"status": "REFUSED", "ok": False, "reasons": [why], "refused": why}


def _backup_name(aep: Path, tag: str) -> Path:
    import time
    d = aep.parent / "backups"
    while True:
        t = time.time()
        p = d / f"{aep.stem}.{tag}-{time.strftime('%Y%m%d-%H%M%S', time.localtime(t))}-{int(t % 1 * 1e6):06d}{aep.suffix}"
        if not p.exists():
            return p


def _build_locked(paths, replace_edited: bool, allow_fallback_font: bool, timeout: int, made: dict | None = None) -> dict:
    import platform as _pf
    import shutil
    import time
    from . import ae_bridge
    from .common import set_status
    from .motion_config import format_spec, motion_cfg
    from .motion_readback import compare
    aep = aep_path(paths)
    base = {"status": "REFUSED", "reasons": [], "aep": str(aep), "fallback_font": None}
    edited = editor_changed(paths)
    if edited and not replace_edited:       # a refusal (exit 2), like ppro-build's EDITOR_CHANGES_PRESENT (Gate 2 A2)
        why = ("the editor changed the .aep since the last build: rebuilding would discard that work - "
               "`--replace-edited` keeps a backup copy first")
        return dict(base, reasons=[why], blocked="the editor changed the .aep since the last build",
                    how="Ask the editor; only with their OK run motion-build again with --replace-edited (their .aep "
                        "is copied to 04_after_effects/project/backups/ first)")
    probs, ctx = preconditions(paths, allow_fallback_font)
    if probs:
        return dict(base, reasons=probs, **(ctx.get("refusal") or {}))
    from .build_safety import free_space_refusal
    short = free_space_refusal(aep.parent, aep.stat().st_size if aep.exists() else 0)     # G2 R1: before any write
    if short:
        return dict(base, reasons=[short["error"]], **{k: short[k] for k in ("ok", "error", "how", "blocked")})
    if aep.exists():            # only once the build will run: a refused build leaves no backup behind. G2 R1: every
        # rebuild keeps the .aep it replaces (the editor's work, or the pipeline's own), not only an edited one
        bak = _backup_name(aep, "edited" if edited else "prev")
        bak.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.copy2(aep, bak)
        except OSError:
            bak.unlink(missing_ok=True)         # a half copy is no backup
            raise
        if made is not None:
            made["backup"] = bak
    fb, fb_plan, brand = None, None, []
    if ctx.get("missing_fonts") and allow_fallback_font:
        from .motion_layout import find_font_face
        from .motion_plan import compile_motion
        fbs = motion_cfg().get("fallback_fonts") or {}
        fb = fbs.get("mac" if _pf.system() == "Darwin" else "windows")
        fface = find_font_face(fb) if fb else None      # file AND face index: GeezaPro-Bold is face 1 of GeezaPro.ttc
        if not fface:
            return dict(base, reasons=[f"the fallback font {fb!r} is not installed either: install the brand fonts"])
        # re-fit the layout with the font After Effects will draw (same words: the Gate 1 approval stays valid), for
        # this job only: the approved plan keeps the brand fonts, so a rebuild after installing them uses them
        rc = compile_motion(paths, font_override={"ps": fb, "file": fface["file"], "index": fface["index"]},
                            write=False)
        if not rc["ok"]:
            return _record(paths, dict(base, status="FAILED", reasons=["re-fit with the fallback font: " + e
                                                                        for e in rc["errors"]], fallback_font=fb))
        fb_plan, brand = rc["plan_data"], ctx["missing_fonts"]
    job_p = write_job(paths, fallback_font=fb, plan=fb_plan)
    job = json.loads(job_p.read_text(encoding="ascii"))
    t0 = time.time()
    r = ae_bridge.submit("build_motion", {"job": job}, timeout=timeout)
    rep = _inner(r)
    if rep.get("reason") in ("dirty", "dirty_target"):
        return dict(base, reasons=[f"After Effects has unsaved changes in {rep.get('project') or 'a project'}: save or "
                                   "close it in After Effects first"])
    fresh = aep.exists() and aep.stat().st_mtime >= t0 - 1
    if not r.get("ok") or not fresh:
        return _record(paths, dict(base, status="FAILED", reasons=[r.get("error") or "build failed or the .aep was not saved"],
                                   report=rep, fallback_font=fb))
    rb = _inner(ae_bridge.submit("readback", {"job": job}, timeout=300))
    cmp_ = compare(job["plan"], rb, format_spec(job["plan"]["format"]), job["caps"])
    ok = cmp_["ok"] and not rep.get("failed")
    fails = cmp_["failures"] + [f"{f.get('scene')}: {f.get('error')}" for f in rep.get("failed") or []]
    warnings = []
    if fb:                      # the editor must see it in the warnings, not only in a field (Gate 2 live check)
        warnings.append(f"built with the fallback font {fb} instead of the brand font(s) {', '.join(brand)} (not "
                        "installed for After Effects): install them from assets/Fonts and run motion-build again to "
                        "use the brand fonts")
    res = dict(base, status="PROJECT_ASSEMBLED" if ok else "FAILED", reasons=[] if ok else fails, report=rep,
               warnings=warnings,
               readback=rb, comparison=cmp_, aep_sha1=_sha1(aep), fallback_font=fb, brand_fonts=brand,
               caps_source=job.get("caps_source"),
               plan_fingerprint=job["plan"].get("fingerprint"))
    _record(paths, res)
    if ok:
        set_status(paths, "PROJECT_ASSEMBLED", "AE motion project built and read back", "motion_build", [str(aep)])
    return res


def script_only(paths) -> dict:
    refused = _route_refused(paths)
    if refused:
        return refused
    jsx = write_fallback_script(paths)
    return {"status": "SCRIPT_ONLY", "jsx": str(jsx), "aep": str(aep_path(paths)),
            "next": "run it in After Effects (File > Scripts > Run Script File...); it is not verified: no read-back"}


def _ae_titles() -> list[str]:
    """After Effects' main window titles (Windows; [] elsewhere, or when it is not running)."""
    from . import plat
    from .common import run
    if not plat.IS_WIN:
        return []
    try:
        p = run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
                 "[Console]::OutputEncoding=[Text.Encoding]::UTF8; Get-Process AfterFX -ErrorAction SilentlyContinue | "
                 "ForEach-Object { $_.MainWindowTitle }"], check=False, timeout=60, encoding="utf-8")
    except Exception:  # noqa: BLE001 — no PowerShell or a hung query: the script still refuses on its own
        return []
    return [ln.strip() for ln in (p.stdout or "").splitlines() if ln.strip()]


def unsaved_project(titles: list[str]) -> str | None:
    """The project's file name when an After Effects title marks unsaved changes: AE 26.5 shows
    "Adobe After Effects 2026 - <path, elided in the middle>.aep *" (seen live)."""
    from pathlib import PureWindowsPath
    for t in titles:
        t = t.rstrip()
        if t.endswith("*") and " - " in t:
            return PureWindowsPath(t[:-1].rstrip().split(" - ", 1)[1]).name or "an untitled project"
    return None


def _refusal(project: str) -> str:
    return (f"After Effects has unsaved changes in {project}: save or close it in After Effects first, then run "
            "`motion-build --run-script` again (the script never discards them)")


def run_script(paths, timeout: int = 900) -> dict:
    import time
    from .adobe_run import run_after_effects
    refused = _route_refused(paths)
    if refused:
        return refused
    aep = aep_path(paths)
    busy = unsaved_project(_ae_titles())       # the script would refuse inside AE: say so now, not after --timeout
    if busy:
        return {"status": "REFUSED", "aep": str(aep), "reasons": [_refusal(busy)]}
    jsx = write_fallback_script(paths)
    t0 = time.time()
    r = run_after_effects(jsx, timeout, done=lambda: aep.exists() and aep.stat().st_mtime >= t0 - 1)
    # Nothing ran in AE and the .aep on disk is unchanged: motion-build-result.json is kept as it was (no _record)
    if r.get("status") in ("UNSUPPORTED", "REFUSED", "SCRIPT_STAGE_FAILED"):    # nothing built is never exit 0; REFUSED:
        return dict(r, ok=False, jsx=str(jsx))           # the sandbox, or the build lock (`blocked`: exit 2)
    said = next((ln.split(REFUSED_MARK, 1)[1].strip() for ln in str(r.get("stdout") or "").splitlines()
                 if REFUSED_MARK in ln), None)            # macOS: osascript prints the script's result
    if said is not None:
        return {"status": "REFUSED", "jsx": str(jsx), "aep": str(aep), "reasons": [_refusal(said or "a project")]}
    fresh = aep.exists() and aep.stat().st_mtime >= t0 - 1
    why = ["no read-back: the bridge was not used, so QC cannot pass"] if fresh else [
        f"the .aep was not saved within {timeout} s: After Effects may be showing why (an alert when its open project "
        "has unsaved changes, or it cannot tell - they are never discarded; or a script error). Save or close the open "
        "project and run again, or use --script-only and run the script yourself"]
    # BUILT_UNVERIFIED is not a pass (no read-back, QC cannot pass): ok false, exit 1 (Gate 2 minor)
    res = {"status": "BUILT_UNVERIFIED" if fresh else "FAILED", "ok": False, "jsx": str(jsx), "aep": str(aep),
           "readback": None, "aep_sha1": _sha1(aep) if fresh else "", "reasons": why}
    res.update({k: r[k] for k in ("script_copy_used", "script_copy_kept_until") if k in r})   # the -r copy
    return _record(paths, res)
