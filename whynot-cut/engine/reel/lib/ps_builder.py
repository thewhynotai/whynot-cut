"""Photoshop: generate + (optionally) execute a JSX that builds layered PSDs.

Jobs come from edit-decisions.json -> global.photoshop_jobs (authored by Claude), e.g.
  {"id": "PS_COVER", "kind": "cover", "image": "assets/Photos/4.jpg",
   "headline": "...", "subline": "...", "band": [1150, 1920]}
"""
from __future__ import annotations

import json
import time
from pathlib import Path

from .common import TEMPLATES_DIR, Paths, brand_fallback, now_iso, read_json, run, write_json, write_text
from .ae_builder import fonts_map


def generate(paths: Paths) -> dict:
    ed = read_json(paths.p("01_analysis/edit-decisions.json"), {})
    jobs = ed.get("global", {}).get("photoshop_jobs", [])
    man = read_json(paths.client_db / "asset-manifest.json", {"assets": []})
    by_rel = {a["rel"]: a for a in man["assets"]}
    logo = next((a for a in man["assets"] if a["category"] == "logo"), None)
    tok = read_json(paths.client_db / "branding/brand-tokens.json", {})
    hx = lambda h: [int(h.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4)]
    brand = {"teal": hx(tok.get("roles", {}).get("primary", {}).get("hex", brand_fallback("primary"))),
             "white": hx(tok.get("roles", {}).get("neutral_light", {}).get("hex", brand_fallback("neutral_light"))),
             "paper": hx(tok.get("derived", {}).get("paper_tint", {}).get("hex", brand_fallback("paper_tint"))),
             "ink": hx(tok.get("derived", {}).get("ink", {}).get("hex", brand_fallback("ink")))}
    errors = []
    for j in jobs:
        if j.get("image"):
            a = by_rel.get(j["image"])
            if not a:
                errors.append(f"{j['id']}: image {j['image']} not in client asset manifest")
                continue
            j["image_name"] = Path(j["image"]).name
            # full-res original for print-quality layers (RAW -> its JPEG derivative)
            j["image"] = a.get("raw_derivative") or a["file"]
        from .ae_builder import wrap_lines
        for k, mx in (("headline", 20), ("subline", 34)):
            if j.get(k):
                j[k] = wrap_lines(j[k], j.get(k + "_max_chars", mx))   # '\r' = PS line break
        for k in ("headline_color", "subline_color"):
            if isinstance(j.get(k), str) and j[k] in brand:
                j[k] = brand[j[k]]
    out_dir = paths.p("05_photoshop/layered-assets")
    data = {"jobs": jobs, "brand": brand, "fonts": fonts_map(paths.client_db),
            "logo": logo["file"] if logo else None, "out_dir": str(out_dir), "generated": now_iso()}
    lib = (TEMPLATES_DIR / "photoshop/nh_ps_lib.jsx").read_text(encoding="utf-8")
    js = ("// AUTO-GENERATED by whynot-cut — " + now_iso() + "\n"
          + lib.replace("#target photoshop\n", "#target photoshop\nvar NH_PS = " + json.dumps(data, ensure_ascii=True, indent=1) + ";\n", 1)
          + "\nNHPS.build();\n")
    p = paths.p(f"05_photoshop/scripts/build_{paths.video_id}_psd.jsx")
    write_text(p, js)
    return {"jsx": str(p), "jobs": len(jobs), "errors": errors}


def execute(paths: Paths, jsx: Path, timeout: int = 900) -> dict:
    from .adobe_run import run_photoshop
    t0 = time.time()
    res = run_photoshop(jsx, timeout)
    if res.get("status") in ("UNSUPPORTED", "REFUSED"):      # nothing ran: keep the precise status (T2.16)
        return dict(res, ok=False)
    outs = sorted(str(x) for x in paths.p("05_photoshop/layered-assets").glob("*.psd")
                  if not x.name.startswith("._") and x.stat().st_mtime >= t0 - 1)   # saved during THIS run
    res.update(psd=outs, status="PSD_CREATED" if outs else "FAILED")
    if not outs:
        res["ok"] = False             # T2.2 exit-code rule: nothing saved this run is a failure
    write_json(paths.p("05_photoshop/ps-build-result.json"), dict(res, at=now_iso()))
    return res
