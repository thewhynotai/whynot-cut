class TestLockParsing(unittest.TestCase):
    def test_parse_joins_continuations_and_keeps_hashes(self):
        lock = R.parse_lock(LOCK_TEXT)
        self.assertEqual(set(lock), {"faster-whisper", "numpy", "pyobjc-core"})
        self.assertEqual(lock["faster-whisper"]["version"], "1.2.1")
        self.assertEqual(lock["faster-whisper"]["hashes"], [H1, H2])
        self.assertEqual(lock["faster-whisper"]["name"], "Faster_Whisper")
        self.assertIsNone(lock["numpy"]["marker"])
        self.assertEqual(lock["pyobjc-core"]["marker"], "sys_platform == 'darwin'")

    def test_unpinned_or_unhashed_lines_are_refused(self):
        with self.assertRaises(ValueError):
            R.parse_lock("numpy>=2 \\\n    --hash=" + H1 + "\n")
        with self.assertRaises(ValueError):
            R.parse_lock("numpy==2.5.4\n")

    def test_normalize(self):
        self.assertEqual(R.normalize("Python_Bidi"), "python-bidi")
        self.assertEqual(R.normalize("pyobjc.framework__Vision"), "pyobjc-framework-vision")

    def test_shipped_locks_are_complete_and_hashed(self):
        for key in PLATFORMS:
            with self.subTest(platform=key):
                f = LOCKS / f"runtime-{key}.lock"
                data = f.read_bytes()
                self.assertNotIn(b"\r", data, "LF only: the runtime id is the sha256 of these bytes")
                self.assertIn(b"uv pip compile setup/requirements.txt --generate-hashes", data)
                lock = R.parse_lock(data.decode("utf-8"))
                self.assertEqual(lock["faster-whisper"]["version"], "1.2.1")
                for name in ("ctranslate2", "av", "numpy", "pillow", "uharfbuzz", "fonttools", "python-bidi",
                             "arabic-reshaper", "freetype-py", "pypdf", "imageio-ffmpeg", "huggingface-hub"):
                    self.assertIn(name, lock)
                    self.assertTrue(lock[name]["hashes"])
                if key == "win-x64":
                    self.assertIn("opencv-python-headless", lock)
                    self.assertNotIn("pyobjc-core", lock)
                else:
                    self.assertIn("pyobjc-framework-coretext", lock)
                    self.assertNotIn("opencv-python-headless", lock)

    def test_locks_follow_the_requirements_pins(self):
        """Every exact pin of requirements.txt (that applies to the platform) is the locked version."""
        pins = {}
        for line in (SK / "setup" / "requirements.txt").read_text(encoding="utf-8").splitlines():
            spec = line.split("#", 1)[0].strip()
            if "==" in spec and ";" not in spec:
                n, v = spec.split("==")
                pins[R.normalize(n.strip())] = v.strip()
        self.assertIn("faster-whisper", pins)
        for key in PLATFORMS:
            lock = R.parse_lock((LOCKS / f"runtime-{key}.lock").read_text(encoding="utf-8"))
            for n, v in pins.items():
                self.assertEqual(lock[n]["version"], v, f"{key}: {n}")


