class FakeRunner:
    """Records setup steps; `uv venv` / `-m venv` create the interpreter file; the smoke import can fail."""

    def __init__(self, smoke_ok=True):
        self.cmds, self.smoke_ok = [], smoke_ok

    def __call__(self, cmd, env=None):
        cmd = [str(c) for c in cmd]
        self.cmds.append(cmd)
        if "venv" in cmd[1:3]:
            py = plat.env_python(Path(cmd[-1]))
            py.parent.mkdir(parents=True, exist_ok=True)
            py.write_text("", encoding="utf-8")
        if "-c" in cmd and cmd[-1].startswith("import ") and not self.smoke_ok:
            raise SETUP.Failed("smoke", detail="ImportError: av")
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    def verbs(self):
        return [" ".join(c[1:3]) for c in self.cmds]


