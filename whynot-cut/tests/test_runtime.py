class TestRuntimeId(unittest.TestCase):
    def test_placeholder_gives_the_lock_hash_id(self):
        data = b"numpy==1 \\\n    --hash=" + H1.encode() + b"\n"
        want = "r-" + hashlib.sha256(data).hexdigest()[:12]
        self.assertEqual(R.runtime_id(data, "<release>"), want)
        self.assertEqual(R.runtime_id(data, None), want)
        self.assertEqual(R.runtime_id(data, ""), want)
        self.assertEqual(R.runtime_id(data, "r-7f3a9c21d0e4"), "r-7f3a9c21d0e4")

    def test_shipped_components_and_locks_give_an_id_per_platform(self):
        comp = R.components()
        for key in PLATFORMS:
            with self.subTest(platform=key):
                ent = R.lock_entry(key, comp)
                self.assertEqual(ent["file"], LOCKS / f"runtime-{key}.lock")
                rid = R.runtime_id(ent["file"].read_bytes(), ent["declared_id"])
                self.assertRegex(rid, r"^[A-Za-z0-9][A-Za-z0-9._-]+$")
                self.assertTrue(plat._RUNTIME_ID.match(rid))

    def test_lock_entry_defaults_without_components(self):
        ent = R.lock_entry("mac-x64", {})
        self.assertEqual(ent["file"].name, "runtime-mac-x64.lock")
        self.assertIsNone(ent["declared_id"])

    def test_platform_key(self):
        self.assertEqual(R.platform_key("Windows", "AMD64"), "win-x64")
        self.assertEqual(R.platform_key("Darwin", "arm64"), "mac-arm64")
        intel, rosetta = (lambda k: None), (lambda k: "1" if k == "sysctl.proc_translated" else None)
        self.assertEqual(R.platform_key("Darwin", "x86_64", sysctl=intel), "mac-x64")      # a real Intel Mac
        self.assertEqual(R.platform_key("Darwin", "x86_64", sysctl=rosetta), "mac-arm64")  # x86_64 Python under Rosetta
        self.assertEqual(R.platform_key("Darwin", "x86_64", sysctl=lambda k: "1" if k == "hw.optional.arm64" else "0"),
                         "mac-arm64")                                                       # Apple Silicon hardware
        self.assertEqual(R.platform_key("Linux", "aarch64"), "linux-arm64")
        self.assertIsNone(R.platform_key("Windows", "sparc"))


