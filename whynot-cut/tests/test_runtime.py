class TestRepairDecision(unittest.TestCase):
    LOCK = R.parse_lock(LOCK_TEXT)
    OK = {"faster-whisper": "1.2.1", "numpy": "2.5.4", "pip": "25.0"}

    def decide(self, installed=None, exists=True, stamp="s", sha="s"):
        return R.repair_decision(self.LOCK, self.OK if installed is None else installed, exists=exists,
                                 stamp_sha=stamp, lock_sha=sha)

    def test_no_runtime_means_create(self):
        self.assertEqual(self.decide(exists=False)["action"], "create")

    def test_matching_runtime_needs_nothing(self):
        self.assertEqual(self.decide(), {"action": "none", "reasons": []})

    def test_version_drift_means_sync(self):
        d = self.decide({**self.OK, "numpy": "2.0.2"})
        self.assertEqual(d["action"], "sync")
        self.assertIn("numpy 2.0.2 installed, the lock pins 2.5.4", d["reasons"])

    def test_missing_package_means_sync(self):
        d = self.decide({"numpy": "2.5.4"})
        self.assertEqual(d["action"], "sync")
        self.assertIn("Faster_Whisper missing", d["reasons"])

    def test_lock_hash_change_means_sync(self):
        d = self.decide(stamp="old", sha="new")
        self.assertEqual(d["action"], "sync")
        self.assertIn("lock changed", d["reasons"][0])
        self.assertEqual(self.decide(stamp=None, sha="new")["action"], "sync")

    def test_unlistable_runtime_means_sync(self):
        d = R.repair_decision(self.LOCK, None, exists=True, stamp_sha="s", lock_sha="s")
        self.assertEqual(d["action"], "sync")

    def test_marker_lines_only_checked_when_installed(self):
        self.assertEqual(self.decide()["action"], "none")                       # pyobjc-core absent: fine
        self.assertEqual(self.decide({**self.OK, "pyobjc-core": "10.0"})["action"], "sync")


