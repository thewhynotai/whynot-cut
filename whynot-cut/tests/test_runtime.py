class TestWrappersPickTheRuntime(TempHome):
    """Both wrappers: current runtime (with -s) > legacy venv (as before)."""

    def shells(self):
        out = []
        if IS_WIN:
            out.append(("reel.cmd", run_cmd))
        if git_bash():
            out.append(("bin/reel", run_bash))
        if not out:
            self.skipTest("no shell for either wrapper")
        return out

    def run_all(self, **extra):
        user = self.t / "user"
        user.mkdir(exist_ok=True)
        got = {}
        for name, run in self.shells():
            got[name] = echo_of(*run(["status", "x"], clean_env(user, **extra)))
        return got

    def test_runtime_named_by_current_wins_and_runs_without_user_site(self):
        rt = fake_runtime(self.home, "r-wrap1", real=True)
        fake_venv(self.home, real=True)
        (self.home / "current").write_bytes(b"r-wrap1\r\n")
        for name, got in self.run_all(WHYNOT_HOME=self.home).items():
            with self.subTest(wrapper=name):
                self.assertEqual(norm(got["prefix"]), norm(str(rt)))
                self.assertTrue(got["no_user_site"])
                self.assertEqual(got["argv"], ["status", "x"])

    def test_current_without_its_runtime_falls_back_to_the_venv(self):
        v = fake_venv(self.home, real=True)
        (self.home / "current").write_text("r-missing\n", encoding="utf-8")
        for name, got in self.run_all(WHYNOT_HOME=self.home).items():
            with self.subTest(wrapper=name):
                self.assertEqual(norm(got["prefix"]), norm(str(v)))
                self.assertFalse(got["no_user_site"])

    def test_odd_current_contents_fall_back_to_the_venv(self):
        """A path, quotes, `&` or an empty line in `current`: never a crash, never a path outside runtimes/."""
        v = fake_venv(self.home, real=True)
        fake_runtime(self.home, "r-wrap3", real=True)
        odd = (b"-r1", b".r1", b"r!1", b"r(1)", b"r%PATH%1", b"r^1", b"r" * 81, b"r-wrap3..x")
        for f in odd:          # their folders exist (a broken interpreter): taking one would fail the echo
            fake_runtime(self.home, f.decode())
        for bad in (b'r-x" & echo pwned', b"..\\venv", b"r-wrap3/../..", b"", b"\r\n", b"a:b", *odd):
            (self.home / "current").write_bytes(bad)
            for name, got in self.run_all(WHYNOT_HOME=self.home).items():
                with self.subTest(wrapper=name, current=bad):
                    self.assertEqual(norm(got["prefix"]), norm(str(v)))

    def test_default_home_with_only_a_runtime(self):
        user = self.t / "user"
        new = user / ".whynot-cut"
        rt = fake_runtime(new, "r-wrap2", real=True)
        (new / "current").write_text("r-wrap2", encoding="utf-8")
        fake_venv(user / ".reel-editor")                      # a legacy home must not win over it
        for name, got in self.run_all().items():
            with self.subTest(wrapper=name):
                self.assertEqual(norm(got["whynot_home"]), norm(str(new)))
                self.assertEqual(norm(got["prefix"]), norm(str(rt)))


