class TestSetupBuild(TempHome):
    def setUp(self):
        super().setUp()
        self.lock = self.t / "runtime-test.lock"
        self.lock.write_text(LOCK_TEXT, encoding="utf-8")
        self.sha = hashlib.sha256(self.lock.read_bytes()).hexdigest()
        self.comp = {"runtime": {"python": "3.12.15", "smoke": ["faster_whisper"]}}
        self.uv = self.t / "uv.exe"
        self.installed = {"faster-whisper": "1.2.1", "numpy": "2.5.4"}
        quiet = mock.patch.object(SETUP, "say", lambda msg: None)        # progress lines would clutter the run
        quiet.start()
        self.addCleanup(quiet.stop)

    def build(self, runner, **kw):
        kw.setdefault("uv", self.uv)
        kw.setdefault("probe", IS_FILE)
        return SETUP.build(home=self.home, comp=self.comp, key="win-x64", lock_file=self.lock, rid="r-new",
                           runner=runner, versions=lambda py: dict(self.installed), **kw)

    def test_create_installs_python_venv_lock_then_switches(self):
        (self.home / "current").write_text("r-old\n", encoding="utf-8")
        run = FakeRunner()
        rep = self.build(run)
        self.assertEqual(rep["action"], "create")
        c = run.cmds
        self.assertEqual(c[0][1:], ["python", "install", "3.12.15", "--no-bin", "--no-registry"])
        self.assertEqual(c[1][1:6], ["venv", "--python", "3.12.15", "--python-preference", "only-managed"])
        self.assertNotIn("--system-site-packages", c[1])
        rt = self.home / "runtimes" / "r-new"
        self.assertEqual(c[2][1:], ["pip", "sync", "--require-hashes", "--python", str(plat.env_python(rt)),
                                    str(self.lock)])
        self.assertEqual(c[3][1:], ["-s", "-c", "import faster_whisper"])
        self.assertEqual((self.home / "current").read_text(encoding="utf-8"), "r-new\n")
        st = json.loads((rt / "WHYNOT_RUNTIME").read_text(encoding="utf-8"))
        self.assertEqual(set(st), {"id", "platform", "python", "lock_file", "lock_sha256", "created_at", "by"})
        self.assertEqual((st["id"], st["platform"], st["python"], st["lock_sha256"], st["by"]),
                         ("r-new", "win-x64", "3.12.15", self.sha, "reel setup"))
        self.assertEqual((rt / ".whynot-lock.sha256").read_text(encoding="utf-8").strip(), self.sha)
        self.assertEqual((rep["previous"], rep["switched"]), ("r-old", True))
        self.assertFalse(list((self.home / "runtimes").glob(".*.building")))

    def test_smoke_failure_keeps_current_and_stamps_nothing(self):
        (self.home / "current").write_text("r-old\n", encoding="utf-8")
        with self.assertRaises(SETUP.Failed) as cm:
            self.build(FakeRunner(smoke_ok=False))
        self.assertIn("was not changed", str(cm.exception))
        self.assertEqual((self.home / "current").read_text(encoding="utf-8"), "r-old\n")
        self.assertFalse((self.home / "runtimes" / "r-new" / "WHYNOT_RUNTIME").exists())

    def make_built(self, sha=None):
        rt = fake_runtime(self.home, "r-new")
        R.write_stamps(rt, rid="r-new", key="win-x64", python="3.12.15", lock_file="x", lock_sha=sha or self.sha,
                       by="installer")
        R.write_current(self.home, "r-new")
        return rt

    def test_matching_runtime_is_left_alone(self):
        rt = self.make_built()
        run = FakeRunner()
        rep = self.build(run)
        self.assertEqual(rep["action"], "none")
        self.assertEqual(run.verbs(), ["-s -c"])                               # only the smoke import
        self.assertEqual(json.loads((rt / "WHYNOT_RUNTIME").read_text(encoding="utf-8"))["by"], "installer")
        self.assertFalse(rep["switched"])

    def test_version_drift_is_repaired_by_sync(self):
        self.make_built()
