"""Parity test: the English docs-site pages (guide-ar/site/en) against the Arabic ones (guide-ar/site/ar).

Run:  ~/.whynot-cut/venv/Scripts/python.exe -m unittest discover -s guide-ar/tests -v
      python guide-ar/tests/test_site_en.py --only 00-09      (a range or a comma list of chapter numbers)

Standard library only. The Arabic pages are generated by site.py; the English pages are translations,
so this test checks the structure, not the words: every Arabic page has an English page with the same
slug, order, headings, anchors, links, screenshots, 3.0 lines and code, and no Arabic letters are left
in the reader text (Arabic is allowed only inside quotes, parentheses or code: the commands an editor
may type to Claude in Arabic, and the glossary's Arabic terms).
"""
import os
import re
import sys
import unittest
from pathlib import Path

GUIDE = Path(os.environ.get("WNC_GUIDE") or Path(__file__).resolve().parent.parent)
SITE_AR = GUIDE / "site" / "ar"
SITE_EN = GUIDE / "site" / "en"

TODO_AR = r"^\s*> \*\*في الإصدار 3\.0"
TODO_EN = r"^\s*> \*\*In 3\.0 — not verified yet:\*\* \S"
ONLY = os.environ.get("SITE_EN_ONLY", "")  # e.g. "00-09" or "00,03,19"; empty = all pages

_ARABIC = re.compile(r"[؀-ۿݐ-ݿࢠ-ࣿﭐ-﷿ﹰ-﻿]")
_FENCE = re.compile(r"^(\s*)```")


def _wanted(name):
    if not ONLY:
        return True
    num = int(name[:2])
    for part in ONLY.split(","):
        part = part.strip()
        if "-" in part:
            lo, hi = part.split("-", 1)
            if int(lo) <= num <= int(hi):
                return True
        elif part and int(part) == num:
            return True
    return False


def _front(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None, text
    meta = dict(line.split(": ", 1) for line in m.group(1).split("\n"))
    return meta, text[m.end():]


def _split_code(body):
    """(prose lines, fenced blocks) — a block is its lines, fences included, exactly as written."""
    prose, blocks, current = [], [], None
    for line in body.split("\n"):
        if current is None:
            if _FENCE.match(line):
                current = [line]
            else:
                prose.append(line)
        else:
            current.append(line)
            if _FENCE.match(line):
                blocks.append("\n".join(current))
                current = None
    if current is not None:
        blocks.append("\n".join(current))  # unclosed: still compared, so a broken fence shows up
    return prose, blocks


def _headings(prose):
    return [len(m.group(1)) for line in prose for m in [re.match(r"^(#{1,6}) \S", line)] if m]


def _links(prose):
    return re.findall(r"\]\(([^)\s]+)\)", "\n".join(prose))


def _shots(prose):
    return re.findall(r"!\[[^\n]*?\]\(shots/([^)\s]+)\.png\)", "\n".join(prose))


def _todo_by_section(prose, pattern):
    """[(section, number of 3.0 lines in it)] — section is the heading's {#id}, or its position if it has none."""
    sections = [["(top)", 0]]
    for line in prose:
        if re.match(r"^#{1,6} \S", line):
            m = re.search(r"\{#([^}\s]+)\}", line)
            sections.append([m.group(1) if m else f"heading {len(sections)}", 0])
        elif re.match(pattern, line):
            sections[-1][1] += 1
    return [tuple(s) for s in sections]


def _arabic_outside_allowed(prose):
    """Arabic letters left after removing inline code, quoted text and parenthesised text."""
    text = "\n".join(prose)
    text = re.sub(r"`[^`\n]*`", "", text)
    for pattern in (r"«[^»\n]*»", r"“[^”\n]*”", r"\"[^\"\n]*\""):
        text = re.sub(pattern, "", text)
    previous = None
    while previous != text:  # innermost parentheses first, so nested ones go too
        previous = text
        text = re.sub(r"\([^()\n]*\)", "", text)
    return [line.strip() for line in text.split("\n") if _ARABIC.search(line)]


class SiteEnParityTests(unittest.TestCase):
    def test_export_site_en_parity(self):
        ar_pages = [p for p in sorted(SITE_AR.glob("*.md")) if _wanted(p.name)]
        self.assertTrue(ar_pages, f"no Arabic pages in {SITE_AR}")
        if not ONLY:
            self.assertEqual(len(ar_pages), 20)
            en_names = sorted(p.name for p in SITE_EN.glob("*.md"))
            self.assertEqual(en_names, [p.name for p in ar_pages], "site/en has missing or extra pages")
        for ar_path in ar_pages:
            name = ar_path.name
            en_path = SITE_EN / name
            with self.subTest(page=name):
                self.assertTrue(en_path.exists(), f"site/en/{name} is missing")
                ar_text = ar_path.read_text(encoding="utf-8")
                en_text = en_path.read_text(encoding="utf-8")
                ar_meta, ar_body = _front(ar_text)
                en_meta, en_body = _front(en_text)
                self.assertIsNotNone(en_meta, f"{name}: no front matter")
                self.assertEqual(en_meta.get("slug"), ar_meta["slug"], name)
                self.assertEqual(en_meta.get("order"), ar_meta["order"], name)
                self.assertEqual(en_meta.get("lang"), "en", name)
                self.assertEqual(en_meta.get("dir"), "ltr", name)
                title = en_meta.get("title", "").strip().strip('"')
                self.assertTrue(title, f"{name}: empty title")
                self.assertIsNone(_ARABIC.search(title), f"{name}: Arabic in the title")
                self.assertNotIn("<!--", en_text, name)

                ar_prose, ar_code = _split_code(ar_body)
                en_prose, en_code = _split_code(en_body)
                self.assertEqual(_headings(en_prose), _headings(ar_prose), f"{name}: heading count or levels")
                self.assertEqual(re.findall(r"\{#([^}\s]+)\}", "\n".join(en_prose)),
                                 re.findall(r"\{#([^}\s]+)\}", "\n".join(ar_prose)), f"{name}: {{#id}} anchors")
                self.assertEqual(_links(en_prose), _links(ar_prose), f"{name}: link targets")
                self.assertEqual(_shots(en_prose), _shots(ar_prose), f"{name}: screenshot ids")
                self.assertEqual(len(re.findall(TODO_EN, en_body, re.M)),
                                 len(re.findall(TODO_AR, ar_body, re.M)), f"{name}: 3.0 lines")
                # Same count in the same section: a 3.0 line moved to another section must fail.
                self.assertEqual(_todo_by_section(en_prose, TODO_EN), _todo_by_section(ar_prose, TODO_AR),
                                 f"{name}: 3.0 lines per section")
                self.assertEqual(en_code, ar_code, f"{name}: fenced code blocks differ")
                left = _arabic_outside_allowed(en_prose)
                self.assertEqual(left, [], f"{name}: Arabic outside quotes, parentheses or code")


if __name__ == "__main__":
    if "--only" in sys.argv:
        i = sys.argv.index("--only")
        ONLY = sys.argv[i + 1]
        del sys.argv[i:i + 2]
    unittest.main()
